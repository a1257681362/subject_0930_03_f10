-- museum-8 虫害监测
--   设计要点：
--   1) 诱捕点位（t_pest_trap_point）设在展厅（HALL）与库房（STORAGE）：
--      编号全库唯一，登记布放日期、坐标与责任区域；点位迁移不原地改坐标，
--      写入 t_pest_point_move 保留前后坐标，点位行更新为当前坐标。
--   2) 诱捕片（t_pest_trap_card）按点位布放/更换：更换只把旧片置
--      REPLACED 并布放新片，旧片与其监测记录永不删除。
--   3) 虫种阈值规则按版本发布（t_pest_rule_version + t_pest_rule_item），
--      只追加不改写：发布新版本旧版本置 SUPERSEDED；监测记录固化规则版本
--      快照与判定结论——规则调整只生成新版本，不改写监测记录旧结论。
--   4) 监测记录（t_pest_monitor_record + 明细/照片）：外包人员（OUTSOURCE）
--      与馆内人员（INTERNAL）均可提交现场数据；结论按提交时生效规则版本
--      判定并固化。监测结果按月份冻结（t_pest_month_freeze）：月份冻结后
--      该月记录与照片不再接受补录/更改。
--   5) 任一虫种数量超过阈值即生成处置任务（t_pest_dispose_task）并关联
--      点位责任区域；外包人员不能关闭任务，仅馆内人员可关闭。
--   6) 虫害台账 t_pest_ledger 只追加：规则发布/点位建档迁移/诱捕片布放
--      更换/监测提交/任务生成关闭/月份冻结全部留痕并标明规则版本。
-- ========================================================================

-- ------------------------------------------------------------------------
-- 41. 虫害阈值规则版本：只追加。
--     status: DRAFT 草稿 / ACTIVE 当前生效 / SUPERSEDED 已被新版本取代
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_pest_rule_version (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no       VARCHAR(40)  NOT NULL,
    title            VARCHAR(255) NOT NULL,
    remark           VARCHAR(500),
    status           VARCHAR(16)  NOT NULL DEFAULT 'DRAFT',
    published_by     VARCHAR(64),
    published_at     TIMESTAMP,
    create_by        BIGINT,
    create_time      TIMESTAMP,
    update_by        BIGINT,
    update_time      TIMESTAMP,
    CONSTRAINT uk_pest_rule_version_no UNIQUE (version_no),
    CONSTRAINT ck_pest_rule_status CHECK (status IN ('DRAFT', 'ACTIVE', 'SUPERSEDED'))
);

-- ------------------------------------------------------------------------
-- 42. 规则条目：每个虫种一行（同版本内虫种唯一），固化阈值数量。
--     监测记录中该虫种数量 > threshold_count 即判定超阈值。
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_pest_rule_item (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_version_id  BIGINT NOT NULL,
    pest_species     VARCHAR(64)  NOT NULL,
    threshold_count  INT NOT NULL,
    create_by        BIGINT,
    create_time      TIMESTAMP,
    update_by        BIGINT,
    update_time      TIMESTAMP,
    CONSTRAINT uk_pest_rule_species UNIQUE (rule_version_id, pest_species),
    CONSTRAINT ck_pest_rule_threshold CHECK (threshold_count >= 0)
);
CREATE INDEX IF NOT EXISTS idx_pest_rule_item_version ON t_pest_rule_item (rule_version_id);

-- ------------------------------------------------------------------------
-- 43. 诱捕点位：展厅/库房布放，编号唯一，登记布放日期/坐标/责任区域。
--     zone_type: HALL 展厅（zone_id 引用 t_hall）/ STORAGE 库房（引用 t_storage_area）
--     status: ACTIVE 在用 / RETIRED 停用（停用不删历史）
--     坐标为当前坐标；历史坐标见 t_pest_point_move。
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_pest_trap_point (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    point_no         VARCHAR(40)  NOT NULL,
    zone_type        VARCHAR(16)  NOT NULL,
    zone_id          BIGINT NOT NULL,
    zone_name        VARCHAR(128) NOT NULL,
    responsible_area VARCHAR(128) NOT NULL,
    coord_x          DECIMAL(12,4) NOT NULL,
    coord_y          DECIMAL(12,4) NOT NULL,
    deployed_at      TIMESTAMP NOT NULL,
    deployed_by      VARCHAR(64)  NOT NULL,
    status           VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    create_by        BIGINT,
    create_time      TIMESTAMP,
    update_by        BIGINT,
    update_time      TIMESTAMP,
    CONSTRAINT uk_pest_point_no UNIQUE (point_no),
    CONSTRAINT ck_pest_point_zone CHECK (zone_type IN ('HALL', 'STORAGE')),
    CONSTRAINT ck_pest_point_status CHECK (status IN ('ACTIVE', 'RETIRED'))
);
CREATE INDEX IF NOT EXISTS idx_pest_point_zone ON t_pest_trap_point (zone_type, zone_id);

-- ------------------------------------------------------------------------
-- 44. 点位迁移：只追加。保留迁移前后坐标，点位行更新为当前坐标。
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_pest_point_move (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    point_id         BIGINT NOT NULL,
    from_x           DECIMAL(12,4) NOT NULL,
    from_y           DECIMAL(12,4) NOT NULL,
    to_x             DECIMAL(12,4) NOT NULL,
    to_y             DECIMAL(12,4) NOT NULL,
    reason           VARCHAR(500),
    moved_by         VARCHAR(64)  NOT NULL,
    moved_at         TIMESTAMP NOT NULL,
    create_by        BIGINT,
    create_time      TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_pest_move_point ON t_pest_point_move (point_id);

-- ------------------------------------------------------------------------
-- 45. 诱捕片：按点位布放/更换。更换只把旧片置 REPLACED 并布放新片，
--     旧片与其监测记录永不删除。
--     status: ACTIVE 在布 / REPLACED 已更换
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_pest_trap_card (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_no          VARCHAR(40)  NOT NULL,
    point_id         BIGINT NOT NULL,
    deployed_at      TIMESTAMP NOT NULL,
    deployed_by      VARCHAR(64)  NOT NULL,
    replaced_at      TIMESTAMP,
    replaced_by      VARCHAR(64),
    status           VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    create_by        BIGINT,
    create_time      TIMESTAMP,
    update_by        BIGINT,
    update_time      TIMESTAMP,
    CONSTRAINT uk_pest_card_no UNIQUE (card_no),
    CONSTRAINT ck_pest_card_status CHECK (status IN ('ACTIVE', 'REPLACED'))
);
CREATE INDEX IF NOT EXISTS idx_pest_card_point ON t_pest_trap_card (point_id, status);

-- ------------------------------------------------------------------------
-- 46. 监测记录：一次现场提交一行，固化规则版本快照与判定结论。
--     规则调整只生成新版本，不改写本表旧结论。
--     conclusion: NORMAL 正常 / OVER_THRESHOLD 超阈值
--     submitter_role: INTERNAL 馆内人员 / OUTSOURCE 外包人员（均可提交现场数据）
--     monitor_month: 监测月份 yyyy-MM，用于按月份冻结。
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_pest_monitor_record (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    record_no        VARCHAR(40)  NOT NULL,
    point_id         BIGINT NOT NULL,
    card_id          BIGINT NOT NULL,
    rule_version_id  BIGINT NOT NULL,
    rule_version_no  VARCHAR(40)  NOT NULL,
    monitor_month    VARCHAR(7)   NOT NULL,
    conclusion       VARCHAR(16)  NOT NULL,
    over_species     VARCHAR(500),
    submitted_by     VARCHAR(64)  NOT NULL,
    submitter_role   VARCHAR(16)  NOT NULL,
    submitted_at     TIMESTAMP NOT NULL,
    create_by        BIGINT,
    create_time      TIMESTAMP,
    CONSTRAINT uk_pest_record_no UNIQUE (record_no),
    CONSTRAINT ck_pest_record_conclusion CHECK (conclusion IN ('NORMAL', 'OVER_THRESHOLD')),
    CONSTRAINT ck_pest_record_role CHECK (submitter_role IN ('INTERNAL', 'OUTSOURCE'))
);
CREATE INDEX IF NOT EXISTS idx_pest_record_point ON t_pest_monitor_record (point_id, monitor_month);
CREATE INDEX IF NOT EXISTS idx_pest_record_month ON t_pest_monitor_record (monitor_month);

-- 监测记录单号序列：PM-000001 在插入前取号，全库唯一
CREATE SEQUENCE IF NOT EXISTS seq_pest_record_no START WITH 1 INCREMENT BY 1;

-- ------------------------------------------------------------------------
-- 47. 监测明细：每个虫种一行，固化当时阈值快照与是否超阈值。
