-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_pest_monitor_detail (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    record_id        BIGINT NOT NULL,
    pest_species     VARCHAR(64)  NOT NULL,
    pest_count       INT NOT NULL,
    threshold_count  INT,
    over_threshold   INT NOT NULL DEFAULT 0,
    create_by        BIGINT,
    create_time      TIMESTAMP,
    CONSTRAINT uk_pest_detail_species UNIQUE (record_id, pest_species),
    CONSTRAINT ck_pest_detail_count CHECK (pest_count >= 0),
    CONSTRAINT ck_pest_detail_over CHECK (over_threshold IN (0, 1))
);
CREATE INDEX IF NOT EXISTS idx_pest_detail_record ON t_pest_monitor_detail (record_id);

-- ------------------------------------------------------------------------
-- 48. 监测现场照片：复用影像归档内容寻址（t_photo_file），一行一张只追加。
