-- museum-6 文物借展协议与押运闭环
--   设计要点：
--   1) 借展协议（t_loan_agreement + t_loan_agreement_version）登记借展方、
--      保险金额、运输路线与归还日期；协议变更必须另出新版本，版本号协议内递增，
--      新版本签署后旧版本置 SUPERSEDED——已签协议不可直接覆盖，旧版本及其清单
--      快照永不改写（与 museum-4 方案版本同一口径）。
--   2) 借展清单（t_loan_manifest_line）随协议版本固化快照；归还验收以出库时
--      签署版本的清单为「原借展清单」逐项比对。
--   3) 押运节点（t_loan_escort_node）固定 封箱 SEAL -> 交接 HANDOVER
--      -> 到馆 ARRIVAL -> 开箱 OPEN_BOX 四节点，节点必须按序登记、每类仅一条；
--      任一节点登记异常后后续节点一律暂停，异常解除后才能继续；
--      开箱必须两名不同见证人。
--   4) 首节点封箱即向 t_relic_loan 写一条 LENT 贯通记录（不另起占用口径），
--      外借在途期间修复开工、文物撤销、重复借出继续受 museum-1 跨业务校验约束；
--      归还验收闭环时同步置 RETURNED。
--   5) 归还验收（t_loan_return_check + _line）按原清单逐行给相符/损伤/缺失，
--      差异逐行持久化保留；一个协议只允许一条验收记录。
--   6) 协议登记/签署/变更、节点登记/异常/解除、归还验收全部追加写入
--      t_relic_ledger；修复侧可经文物由押运节点反查原单、处理人与异常原因。
-- ========================================================================

