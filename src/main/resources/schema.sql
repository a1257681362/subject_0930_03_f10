-- ========================================================================
-- museum-9 修复工时与设备排程
--   设计要点：
--   1) 修复设备档案（t_repair_equipment）：编号唯一；状态 ACTIVE/FAULT，
--      故障只置状态，历史排程与工时事实永不删改。
--   2) 工时按版本管理（t_repair_timesheet）：修复师每次填报形成一个新版本，
--      负责人审核通过 APPROVED / 退回 RETURNED；退回版本封存只读，
--      补充只能另开新版本（uk 工单+版本号）。
--   3) 工时明细行（t_repair_timesheet_line）固化起止时间/工序/设备，
--      起止可跨天且原样落库；跨天作业在统计口径上按自然日拆分，不拆改原行。
--   4) 设备互斥：SUBMITTED/APPROVED 版本的明细行参与占用；同一设备时段
--      重叠且属于另一个修复中工单即拒绝（设备行锁串行化并发）。
--   5) 设备故障（t_repair_equipment_fault）自动生成改期建议
--      （t_repair_reschedule_suggestion，uk 故障+工时行幂等）：建议固化
--      原时段与建议时段快照，处理只改建议状态——原排程绝不被悄悄改写，
--      实际改期只能走工时单新版本。
--   6) 排程查询同口径：页面/CSV导出/后台统计共用同一行集；文物 REVOKED
--      后默认不计入，includeRevoked=true 时保留并以 REVOKED 标明。
-- ========================================================================

-- ------------------------------------------------------------------------
-- 52. 修复设备档案
--     status: ACTIVE 在用 / FAULT 故障中
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_repair_equipment (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_no     VARCHAR(40)  NOT NULL,
    name             VARCHAR(128) NOT NULL,
    category         VARCHAR(64),
    location         VARCHAR(255),
    status           VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    remark           VARCHAR(500),
    create_by        BIGINT,
    create_time      TIMESTAMP,
    update_by        BIGINT,
    update_time      TIMESTAMP,
    CONSTRAINT uk_repair_equipment_no UNIQUE (equipment_no),
    CONSTRAINT ck_repair_equipment_status CHECK (status IN ('ACTIVE', 'FAULT'))
);

-- ------------------------------------------------------------------------
-- 53. 修复工时单版本：一工单多版本，同时只允许一个待审核版本
--     status: SUBMITTED 待审核 / APPROVED 审核通过 / RETURNED 已退回（封存只读）
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_repair_timesheet (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id       BIGINT NOT NULL,
    version_no       INT NOT NULL,
    restorer         VARCHAR(64)  NOT NULL,
    status           VARCHAR(16)  NOT NULL DEFAULT 'SUBMITTED',
    submitted_by     VARCHAR(64)  NOT NULL,
    submitted_at     TIMESTAMP NOT NULL,
    reviewed_by      VARCHAR(64),
    reviewed_at      TIMESTAMP,
    review_opinion   VARCHAR(500),
    create_by        BIGINT,
    create_time      TIMESTAMP,
    update_by        BIGINT,
    update_time      TIMESTAMP,
    CONSTRAINT uk_timesheet_version UNIQUE (project_id, version_no),
    CONSTRAINT ck_timesheet_status CHECK (status IN ('SUBMITTED', 'APPROVED', 'RETURNED'))
);
CREATE INDEX IF NOT EXISTS idx_timesheet_project ON t_repair_timesheet (project_id, status);

-- ------------------------------------------------------------------------
-- 54. 工时明细行：起止时间/工序/设备原样落库（可跨天），随版本封存不删改
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_repair_timesheet_line (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timesheet_id     BIGINT NOT NULL,
    line_no          INT NOT NULL,
    work_step        VARCHAR(128) NOT NULL,
    equipment_id     BIGINT NOT NULL,
    start_time       TIMESTAMP NOT NULL,
    end_time         TIMESTAMP NOT NULL,
    create_by        BIGINT,
    create_time      TIMESTAMP,
    update_by        BIGINT,
    update_time      TIMESTAMP,
    CONSTRAINT ck_ts_line_time CHECK (end_time > start_time)
);
CREATE INDEX IF NOT EXISTS idx_ts_line_sheet ON t_repair_timesheet_line (timesheet_id);
CREATE INDEX IF NOT EXISTS idx_ts_line_equipment ON t_repair_timesheet_line (equipment_id, start_time, end_time);

-- ------------------------------------------------------------------------
-- 55. 设备故障单：登记故障发生与预计恢复时刻
